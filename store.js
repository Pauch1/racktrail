if (connectionString) {
  const { default: pg } = await import('pg');
  pool = new pg.Pool({
    connectionString,
    max: 5,
    types: {
      getTypeParser(oid, format) {
        if (oid !== 20) return pg.types.getTypeParser(oid, format);
        return value => {
          const number = Number(value);
          if (!Number.isSafeInteger(number)) throw new Error('Database integer exceeds the supported range.');
          return number;
        };
      }
    }
  });
  const postgresSchema = schema
    .replaceAll('id INTEGER PRIMARY KEY', 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\b(expires|price|total|penalty) INTEGER\b/g, '$1 BIGINT');
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock($1)', [transactionLock]);
    await client.query(postgresSchema);
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
} else {
  const { DatabaseSync } = await import('node:sqlite');
  if (file !== ':memory:') mkdirSync(dirname(file), { recursive: true });
  db = new DatabaseSync(file);
  db.exec('PRAGMA busy_timeout = 5000; PRAGMA journal_mode = WAL;');
  db.exec(schema);
}

const columnNames = {
  userid: 'userId', itemid: 'itemId', itemname: 'itemName', rentalid: 'rentalId',
  senderid: 'senderId', paidat: 'paidAt', hasreceipt: 'hasReceipt', displaystatus: 'displayStatus',
  itemcount: 'itemCount', usercount: 'userCount'
};

function postgresSql(sql) {
  let index = 0;
  return sql.replace(/('(?:''|[^'])*')|\?/g, (match, literal) => literal ?? '$' + (++index));
}

function enqueue(work) {
  const result = queue.then(work);
  queue = result.catch(() => {});
  return result;
}

async function query(sql, args, mode) {
  const context = transaction.getStore();
  if (context && !context.active) throw new Error('The database transaction has already completed.');
  const execute = async () => {
    if (db) return db.prepare(sql)[mode](...args);
    const generatedId = mode === 'run' && /^\s*INSERT\s+INTO\s+(users|items|rentals|messages|activity|reports)\b/i.test(sql);
    const text = postgresSql(sql) + (generatedId ? ' RETURNING id' : '');
    const result = await (context?.client || pool).query(text, args);
    const rows = result.rows.map(row => Object.fromEntries(
      Object.entries(row).map(([key, value]) => [columnNames[key] || key, typeof value === 'boolean' ? Number(value) : value])
    ));
    if (mode === 'run') return { changes: result.rowCount, lastInsertRowid: rows[0]?.id ?? 0 };
    return mode === 'get' ? rows[0] : rows;
  };
  return db && !context ? enqueue(execute) : execute();
}

export const all = (sql, ...args) => query(sql, args, 'all');
export const get = (sql, ...args) => query(sql, args, 'get');
export const run = (sql, ...args) => query(sql, args, 'run');

export async function atomic(work) {
  if (transaction.getStore()) throw new Error('Nested database transactions are not supported.');
  const execute = async () => {
    const client = pool ? await pool.connect() : null;
    const context = { client, active: true };
    try {
      if (client) {
        await client.query('BEGIN');
        // All inventory mutations share this lock so availability remains correct across service instances.
        await client.query('SELECT pg_advisory_xact_lock($1)', [transactionLock]);
      } else db.exec('BEGIN IMMEDIATE');
      const result = await transaction.run(context, work);
      if (client) await client.query('COMMIT');
      else db.exec('COMMIT');
      return result;
    } catch (error) {
      if (client) await client.query('ROLLBACK');
      else db.exec('ROLLBACK');
      throw error;
    } finally {
      context.active = false;
      client?.release();
    }
  };
  return db ? enqueue(execute) : execute();
}

export async function close() {
  await queue;
  if (pool) await pool.end();
  else db.close();
}
